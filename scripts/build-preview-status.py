#!/usr/bin/env python3
"""Rebuild preview manifest status from scene modules and standalone HTML."""
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PREVIEWS = ROOT / "docs" / "previews"
LIB = ROOT / "docs" / "library.js"

frames = {}
for path in (PREVIEWS / "scenes").glob("*.js"):
    text = path.read_text(encoding="utf-8")
    for match in re.finditer(r'(?:S\[|add\()"([^"]+)"', text):
        frames[match.group(1)] = path.name
    for match in re.finditer(r'lineChart\("([^"]+)"', text):
        frames[match.group(1)] = path.name

files = {
    path.stem: f"previews/{path.name}"
    for path in PREVIEWS.glob("*.html")
    if path.name != "frame.html"
}

src = LIB.read_text(encoding="utf-8")
eq = src.index("=", src.index("window.LIBRARY"))
lib = json.loads(src[eq + 1 :].strip().rstrip(";"))
old = {}
manifest_path = ROOT / "data" / "preview-manifest.json"
if manifest_path.exists():
    for row in json.loads(manifest_path.read_text(encoding="utf-8")):
        old[row["id"]] = row

# Simplified stand-ins stay out of the verified count.
REVIEW = {
    "rb-lanyard": "二维摆绳，不是三维挂绳网格。",
    "animated-letters-shader": "画布逐字位移，不是着色器。",
    "rb-splash-cursor": "粒子飞溅，不是流体方程。",
    "shader-animation-gsap": "自写时间轴驱动像素涟漪，不是 GSAP。",
    "dreamy-particles": "CPU 粒子聚拢，不是 GPGPU。",
    "rb-ferrofluid": "尖刺朝向力场，不是磁流体体积网格。",
}
LIMITS = {
    "cloth-carousel": "质点弹簧网格，不是外部布料求解器。",
    "cinematic-3d-scroll": "透视投影推进，不是外部三维引擎。",
}

manifest = []
for case in lib["cases"]:
    if case["id"] in files:
        status = "ready"
        entry = files[case["id"]]
        mechanism = "standalone-html"
        limitation = LIMITS.get(case["id"], "")
    elif case["id"] in frames:
        status = "ready"
        entry = f"previews/frame.html?id={case['id']}"
        mechanism = frames[case["id"]]
        limitation = LIMITS.get(case["id"], "")
    else:
        status = "todo"
        entry = ""
        mechanism = case["subcategory"]
        limitation = ""
    if case["id"] in REVIEW:
        status = "review"
        limitation = REVIEW[case["id"]]
    manifest.append({
        "id": case["id"],
        "category": case["category"],
        "title": case["title"],
        "intended": case["subcategory"] + " · " + case["trigger"],
        "mechanism": mechanism,
        "status": status,
        "entrypoint": entry,
        "limitation": limitation,
        "evidence": "scripts/test-previews.mjs" if status in ("ready", "review") else "",
    })

manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
payload = {
    item["id"]: {
        "status": item["status"],
        "entry": item["entrypoint"],
        "mechanism": item["mechanism"],
        "limitation": item["limitation"],
    }
    for item in manifest
}
(PREVIEWS / "status.js").write_text(
    "/* Generated by scripts/build-preview-status.py. */\n"
    "window.PREVIEW_STATUS = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)
print(Counter(item["status"] for item in manifest))
